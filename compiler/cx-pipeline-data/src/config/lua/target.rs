use mlua::{AnyUserData, Lua, Result, UserData, UserDataMethods, Value, Variadic};

use super::global;
use super::state::{Shared, TargetDraft};
use super::values::{describe, fail, string};
use crate::config::schema::TargetKind;

pub(super) struct TargetHandle {
    state: Shared,
    index: usize,
}

impl TargetHandle {
    pub fn new(state: Shared, index: usize) -> Self {
        Self { state, index }
    }
}

pub(super) fn register(lua: &Lua, state: &Shared) -> Result<()> {
    global(lua, state, "target", |lua, state, (name, kind): (Value, Value)| {
        let name = string(lua, &name, "target name")?;
        if name.is_empty() {
            return Err(fail(lua, "target names cannot be empty"));
        }
        let kind = match string(lua, &kind, "target kind")?.as_str() {
            "executable" => TargetKind::Executable,
            "library" => TargetKind::Library,
            other => {
                return Err(fail(
                    lua,
                    format!("unknown target kind '{other}', expected executable or library"),
                ));
            }
        };

        let mut borrowed = state.borrow_mut();
        let current = borrowed.current();
        let selectable = &borrowed.packages[current].selectable;
        if selectable.iter().any(|index| borrowed.targets[*index].name == name) {
            return Err(fail(lua, format!("target '{name}' is declared more than once")));
        }
        borrowed.targets.push(TargetDraft {
            name,
            kind,
            package: current,
            matches: Vec::new(),
            excludes: Vec::new(),
            headers: Vec::new(),
        });
        let index = borrowed.targets.len() - 1;
        borrowed.packages[current].selectable.push(index);
        Ok(TargetHandle::new(state.clone(), index))
    })?;
    global(lua, state, "export_target", |lua, state, target: Value| {
        let index = handle(lua, &target)?;
        let mut state = state.borrow_mut();
        state.owned_target(lua, index)?;
        let package = state.package();
        if !package.exported.contains(&index) {
            package.exported.push(index);
        }
        Ok(())
    })?;
    Ok(())
}

fn handle(lua: &Lua, value: &Value) -> Result<usize> {
    let index = value
        .as_userdata()
        .and_then(|userdata: &AnyUserData| userdata.borrow::<TargetHandle>().ok())
        .map(|handle| handle.index);
    index.ok_or_else(|| fail(lua, format!("expected a target, found {}", describe(value))))
}

fn patterns(lua: &Lua, values: Variadic<Value>, what: &str) -> Result<Vec<String>> {
    values.iter().map(|value| string(lua, value, what)).collect()
}

impl UserData for TargetHandle {
    fn add_methods<M: UserDataMethods<Self>>(methods: &mut M) {
        methods.add_method("match", |lua, this, values: Variadic<Value>| {
            let patterns = patterns(lua, values, "match pattern")?;
            this.state.borrow().owned_target(lua, this.index)?;
            this.state.borrow_mut().targets[this.index].matches.extend(patterns);
            Ok(())
        });
        methods.add_method("exclude", |lua, this, values: Variadic<Value>| {
            let patterns = patterns(lua, values, "exclude pattern")?;
            this.state.borrow().owned_target(lua, this.index)?;
            this.state.borrow_mut().targets[this.index].excludes.extend(patterns);
            Ok(())
        });
        methods.add_method("headers", |lua, this, values: Variadic<Value>| {
            let patterns = patterns(lua, values, "header pattern")?;
            let state = this.state.borrow();
            let target = state.owned_target(lua, this.index)?;
            if target.kind != TargetKind::Library {
                return Err(fail(lua, format!("headers are only generated by a library, not '{}'", target.name)));
            }
            drop(state);
            this.state.borrow_mut().targets[this.index].headers.extend(patterns);
            Ok(())
        });
    }
}
