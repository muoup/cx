use mlua::{Lua, Result, UserData, UserDataMethods, Value, Variadic};

use super::global;
use super::package::{prefix, resolve};
use super::state::{FfiIncludeDraft, Shared, TargetDraft};
use super::values::{fail, string};
use crate::config::schema::TargetKind;

pub(super) struct TargetHandle {
    state: Shared,
    index: usize,
}

pub(super) fn register(lua: &Lua, state: &Shared) -> Result<()> {
    global(lua, state, "target", |lua, state, (name, kind): (Value, Value)| {
        let name = string(lua, &name, "target name")?;
        if name.is_empty() {
            return Err(fail(lua, "target names cannot be empty"));
        }
        let kind = match string(lua, &kind, "target kind")?.as_str() {
            "executable" => TargetKind::Executable,
            "ffi-lib" => TargetKind::FfiLib,
            other => {
                return Err(fail(
                    lua,
                    format!("unknown target kind '{other}', expected executable or ffi-lib"),
                ));
            }
        };

        let mut borrowed = state.borrow_mut();
        let current = borrowed.current();
        let duplicate = borrowed
            .targets
            .iter()
            .any(|target| target.package == current && target.name == name);
        if duplicate {
            return Err(fail(lua, format!("target '{name}' is declared more than once")));
        }
        let index = borrowed.targets.len();
        borrowed.targets.push(TargetDraft {
            name,
            kind,
            package: current,
            matches: Vec::new(),
            excludes: Vec::new(),
            headers: Vec::new(),
            ffi_includes: Vec::new(),
        });
        Ok(TargetHandle { state: state.clone(), index })
    })?;
    Ok(())
}

fn patterns(lua: &Lua, values: Variadic<Value>, what: &str) -> Result<Vec<String>> {
    values.iter().map(|value| string(lua, value, what)).collect()
}

impl TargetHandle {
    fn update(&self, lua: &Lua, change: impl FnOnce(&mut TargetDraft)) -> Result<()> {
        self.state.borrow().owned_target(lua, self.index)?;
        change(&mut self.state.borrow_mut().targets[self.index]);
        Ok(())
    }
}

impl UserData for TargetHandle {
    fn add_methods<M: UserDataMethods<Self>>(methods: &mut M) {
        methods.add_method("match", |lua, this, values: Variadic<Value>| {
            let patterns = patterns(lua, values, "match pattern")?;
            this.update(lua, |target| target.matches.extend(patterns))
        });
        methods.add_method("exclude", |lua, this, values: Variadic<Value>| {
            let patterns = patterns(lua, values, "exclude pattern")?;
            this.update(lua, |target| target.excludes.extend(patterns))
        });
        methods.add_method("headers", |lua, this, values: Variadic<Value>| {
            let patterns = patterns(lua, values, "header pattern")?;
            let kind = this.state.borrow().targets[this.index].kind;
            if kind != TargetKind::FfiLib {
                let name = this.state.borrow().targets[this.index].name.clone();
                return Err(fail(lua, format!("headers are only generated by an ffi-lib, not '{name}'")));
            }
            this.update(lua, |target| target.headers.extend(patterns))
        });
        methods.add_method("ffi_lib_c_include", |lua, this, (path, name, alias): (Value, Value, Value)| {
            let package = resolve(lua, &this.state, &path, "ffi_lib_c_include")?;
            let name = string(lua, &name, "ffi-lib name")?;
            let prefix = prefix(lua, &alias)?;
            this.update(lua, |target| target.ffi_includes.push(FfiIncludeDraft { package, name, prefix }))
        });
    }
}
